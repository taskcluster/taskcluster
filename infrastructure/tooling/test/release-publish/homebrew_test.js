import assert from 'node:assert';
import nock from 'nock';
import { publishHomebrew } from '../../src/release-publish/homebrew.js';

const VERSION = '1.2.3';
const ctx = { version: VERSION, tag: `v${VERSION}`, staging: false };
const DOWNLOADS = `/taskcluster/taskcluster/releases/download/v${VERSION}`;
const noop = () => {};

const platform = (block, p) => `    ${block} do
      url "https://github.com/taskcluster/taskcluster/releases/download/v#{version}/taskcluster-${p}.tar.gz",
        verified: "github.com/taskcluster/taskcluster/"
      sha256 "${'0'.repeat(64)}"
    end`;

// A trimmed copy of the cask goreleaser writes (.goreleaser.yaml homebrew_casks).
const CASK = `# This file was generated by GoReleaser. DO NOT EDIT.
cask "taskcluster" do
  name "taskcluster"
  desc "A command-line client for Taskcluster"
  homepage "https://github.com/taskcluster/taskcluster"
  version "${VERSION}"

  on_macos do
${platform('on_intel', 'darwin-amd64')}
${platform('on_arm', 'darwin-arm64')}
  end

  on_linux do
${platform('on_intel', 'linux-amd64')}
${platform('on_arm', 'linux-arm64')}
  end
end
`;

const fakeOctokit = ({ currentCask } = {}) => {
  const commits = [];
  return {
    commits,
    repos: {
      getContent: async () => {
        if (currentCask === undefined) {
          throw Object.assign(new Error('Not Found'), { status: 404 });
        }
        return { data: { type: 'file', sha: 'abc', content: Buffer.from(currentCask).toString('base64') } };
      },
      createOrUpdateFileContents: async params => {
        commits.push(params);
      },
    },
  };
};

suite('release-publish homebrew', () => {
  setup(() => {
    nock.disableNetConnect();
  });

  teardown(() => {
    nock.cleanAll();
    nock.enableNetConnect();
  });

  test('accepts a goreleaser cask and fetches only the URLs built from the tag', async () => {
    const scope = nock('https://github.com');
    for (const p of ['darwin-amd64', 'darwin-arm64', 'linux-amd64', 'linux-arm64']) {
      scope.head(`${DOWNLOADS}/taskcluster-${p}.tar.gz`).reply(200);
    }
    const octokit = fakeOctokit();
    assert.equal(await publishHomebrew({ ctx, octokit, cask: CASK, sleep: noop, log: noop }), 'committed');
    assert(scope.isDone());
    assert.equal(octokit.commits.length, 1);
    assert.equal(Buffer.from(octokit.commits[0].content, 'base64').toString(), CASK);
  });

  test('rejects an off-release URL before any fetch', async () => {
    const cask = CASK.replace(
      'https://github.com/taskcluster/taskcluster/releases/download/v#{version}/taskcluster-linux-arm64.tar.gz',
      'https://evil.example.com/taskcluster-linux-arm64.tar.gz'
    );
    const octokit = fakeOctokit();
    await assert.rejects(publishHomebrew({ ctx, octokit, cask, sleep: noop, log: noop }), /do not match/);
    assert.equal(octokit.commits.length, 0);
  });

  test('rejects a cask with a missing platform before any fetch', async () => {
    const cask = CASK.replace(`${platform('on_arm', 'linux-arm64')}\n`, '');
    const octokit = fakeOctokit();
    await assert.rejects(publishHomebrew({ ctx, octokit, cask, sleep: noop, log: noop }), /do not match/);
    assert.equal(octokit.commits.length, 0);
  });

  test('leaves an up-to-date tap alone without fetching anything', async () => {
    const octokit = fakeOctokit({ currentCask: CASK });
    assert.equal(await publishHomebrew({ ctx, octokit, cask: CASK, sleep: noop, log: noop }), 'up-to-date');
    assert.equal(octokit.commits.length, 0);
  });

  test('refuses to replace a newer version in the tap', async () => {
    const octokit = fakeOctokit({ currentCask: CASK.replace(`version "${VERSION}"`, 'version "1.10.0"') });
    await assert.rejects(
      publishHomebrew({ ctx, octokit, cask: CASK, sleep: noop, log: noop }),
      /refusing to downgrade/
    );
    assert.equal(octokit.commits.length, 0);
  });

  test('updates an older version in the tap', async () => {
    const scope = nock('https://github.com');
    for (const p of ['darwin-amd64', 'darwin-arm64', 'linux-amd64', 'linux-arm64']) {
      scope.head(`${DOWNLOADS}/taskcluster-${p}.tar.gz`).reply(200);
    }
    const octokit = fakeOctokit({ currentCask: CASK.replace(`version "${VERSION}"`, 'version "1.2.2"') });
    assert.equal(await publishHomebrew({ ctx, octokit, cask: CASK, sleep: noop, log: noop }), 'committed');
    assert(scope.isDone());
    assert.equal(octokit.commits[0].sha, 'abc');
  });

  test('refuses staging releases', async () => {
    const octokit = fakeOctokit();
    await assert.rejects(
      publishHomebrew({ ctx: { ...ctx, staging: true }, octokit, cask: CASK, sleep: noop, log: noop }),
      /must never run for staging/
    );
  });
});
